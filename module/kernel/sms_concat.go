// ====================== 长短信（分条）拼接 ======================
//
// 长短信在网络上被拆成多段（每段用户数据不超过 140 字节）分别投递，模组把它们
// 存成多条互不相干的记录。文本模式（AT+CMGF=1）不会暴露 UDH，因此：
//
//	1. 无法知道哪几条属于同一条长短信；
//	2. 更无法知道段序 —— 存储位置的先后顺序完全不可靠。实测同一台模组：
//	     ref=0x5E：位置 1 是第 1 段、位置 0 是第 2 段（逆序）
//	     ref=0x87：位置 3 是第 1 段、位置 4 是第 2 段（正序）
//	     ref=0x4C：位置 7/6/5 分别是第 1/2/3 段（逆序）
//
// 所以必须再读一遍 PDU 模式（AT+CMGF=0 + AT+CMGL=4），从 UDH 的拼接 IE
// （05 00 03 <ref> <total> <seq>）里拿到引用号与段号，才能正确分组、排序。

